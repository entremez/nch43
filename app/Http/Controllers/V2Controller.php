    public static function validar($lote, $samples, $row, $col)
    {
        $validator = Validator::make(
            ['lote' => $lote, 'muestras' => $samples, 'fila' => $row, 'columna' => $col],
            [
                'lote' => 'required|integer|min:1|max:1000000000',
                'muestras' => 'required|integer|min:1|lte:lote',
                'fila' => 'required|integer|between:1,250',
                'columna' => 'required|integer|between:1,20',
            ],
            [
                'lote.max' => 'El lote no puede ser mayor a 1.000.000.000.',
                'muestras.lte' => 'Las muestras no pueden ser más que las unidades del lote.',
                'fila.between' => 'La fila debe estar entre 1 y 250.',
                'columna.between' => 'La columna debe estar entre 1 y 20.',
                'integer' => 'El campo :attribute debe ser un número entero.',
                'min' => 'El campo :attribute debe ser al menos :min.',
                'required' => 'El campo :attribute es obligatorio.',
            ]
        );

        // Se vuelve al formulario de inicio: /form redirige a la URL del muestreo y "volver atrás" haría un bucle
        if($validator->fails())
            throw (new ValidationException($validator))->redirectTo(url('/'));
    }

    public static function nch43($lote, $samples, $row, $col)
    {
        V2Controller::validar($lote, $samples, $row, $col);

        $procedimiento = ProcedimientoHelper::getProcedimientoByLote($lote);
        $digitos = $procedimiento->digits;
        $vertical = $procedimiento->move == "utd";
        $columnas_a_usar = (int) round($digitos / 2);

        // La lectura solo depende de la posición en la tabla (fila y columna). Pasadas todas las posiciones
        // posibles, alguna se repite y desde ahí solo salen números ya leídos: no hay más números nuevos
        $max_lecturas = 250 * ($digitos == 1 ? 40 : 20);

        // Lectura horizontal (1 o 2 dígitos): posición del número dentro de la fila
        $pos = $digitos == 1 ? $col * 2 - 2 : $col - 1;
        $por_fila = 40 / $digitos;

        $valido = 0;
        $salida = [];
        $tomados = []; // valores finales ya leídos, para descartar repetidos (Art. 9)

        while($valido < $samples){
            V2Controller::controlarLecturas(count($salida), $samples, $max_lecturas);

            if($vertical){
                $siguiente = $row == 250 ? 1 : $row + 1; // después de la fila 250 se continúa en la fila 1 (Art. 6.3)
                $sobrepasa = $col + $columnas_a_usar - 1 > 20;

                // Si el número sobrepasa la columna 20 se completa con el comienzo de la fila siguiente (Art. 6.1)
                $number = substr(self::TABLA[$row], $col*2 - 2, $digitos);
                if(strlen($number) < $digitos)
                    $number .= substr(self::TABLA[$siguiente], 0, $digitos - strlen($number));

                $columnas = [];
                for($a = 0; $a < $columnas_a_usar; $a++)
                    $columnas[] = $col + $a > 20 ? $col + $a - 20 : $col + $a;

                $numero = [
                    'fila' => $sobrepasa ? $row." | ".$siguiente : $row,
                    'columna' => implode(' | ', $columnas).' ',
                ];

                if(in_array($row, self::ULTIMAS_FILAS)){ //si la fila actual es la última de la pagina
                    if($col + $columnas_a_usar - 1 >= 20){
                        $row++;
                        $col = $col + $columnas_a_usar - 20;
                    }else{
                        $row = self::PRIMERAS_FILAS[array_search($row, self::ULTIMAS_FILAS)]; //vuelve a la fila inicial de su misma pagina
                        $col = $col + $columnas_a_usar;
                    }
                }else{
                    $row++;
                }
            }else{
                $numero = [
                    'fila' => $row,
                    'columna' => $digitos == 1 ? (intdiv($pos, 2) + 1).".".($pos % 2 + 1) : $pos + 1,
                ];
                $number = substr(self::TABLA[$row], $pos * $digitos, $digitos);

                $pos++;
                if($pos >= $por_fila){
                    $pos = 0;
                    $row++;
                }
            }
            if($row > 250)
                $row = 1;

            V2Controller::operations($procedimiento, $number, $numero, $lote);

            if(isset($tomados[(int) $numero['valor_final']])){
                $numero['valido'] = false;
                $numero['comentario'] = "Número considerado previamente.";
            }
            $tomados[(int) $numero['valor_final']] = true;
            if($numero['valido'])
                $valido++;

            $salida[] = $numero;
        }
        return json_encode($salida);
    }

    public static function operations($procedimiento, $number, &$numero, $lote){
        $numero['valor_original'] = $number;
        if($number == 0){
            $numero['valor_final'] = $procedimiento->max;
            $numero['valido'] = $procedimiento->max<=$lote;
            $numero['operación'] = "NA";
            $numero['comentario'] = "Art. 8. El ". $number ." de la tabla se leerá como ".$procedimiento->max;
        }else{
            if($procedimiento->divider <> 0){
                $resto = $number%$procedimiento->divider;
                $operacion = floor($number/$procedimiento->divider).' x '.$procedimiento->divider.' + '.$resto.' = '.$number;
                if($resto == 0){
                    $numero['valor_final'] = $procedimiento->max;
                    $numero['valido'] = $procedimiento->max<=$lote;
                    $numero['operación'] = $operacion;
                    $numero['comentario'] = "Art. 8. El resto 0 de la tabla se leerá como ".$procedimiento->max;
                }else{
                    $numero['valor_final'] = $resto;
                    $numero['valido'] = $resto<=$lote;
                    $numero['comentario'] = $resto>$lote ? 'Valor final mayor al lote.' : '-';
                    $numero['operación'] = $operacion;
                }
            }else{
                $numero['valor_final'] = $number;
                $numero['valido'] = $number<=$lote;
                $numero['comentario'] = $number>$lote ? 'Valor final mayor al lote.' : '-';
                $numero['operación'] = 'NA';
            }
        }
    }

    public static function controlarLecturas($leidos, $samples, $max_lecturas)
    {
        if($leidos >= $max_lecturas){
            throw ValidationException::withMessages([
                'muestras' => 'La tabla de la norma no contiene '.$samples.' números distintos válidos para este lote. Reduzca la cantidad de muestras.',
            ])->redirectTo(url('/'));
        }
    }

    public static function getView($lote, $samples, $row=null, $column=null){
        $data = V2Controller::nch43($lote, $samples, $row, $column);
        $array_data = json_decode($data);
        $last_number = $array_data[count($array_data) - 1];
        $last_row = explode(" | ", $last_number->fila);
        $last_column = explode(" | ",$last_number->columna);
        return view('welcome', [
             'data'=> $data,
            'lote' => $lote,
            'muestras' => $samples,
            'inicial' => $row.'/'.$column,
            'final' => $last_row[count($last_row) -1].'/'.$last_column[count($last_column) -1]
        ]);
    }

    
